"""
Abstract Embedding Provider Interface (Adapter Pattern).
Enables seamless swapping between Ollama, OpenAI, Cohere, Bedrock, or custom embedding services.
"""

from __future__ import annotations

from abc import ABC, abstractmethod
from typing import Any


class EmbeddingAdapterError(Exception):
    """Base exception for embedding provider failures."""
    pass


class EmbeddingAdapter(ABC):
    """
    Contract for embedding providers.
    Every provider must produce dense float vectors for text inputs.
    """

    @abstractmethod
    async def get_embedding(self, text: str) -> list[float]:
        """Generate a single dense semantic embedding vector for text."""
        pass

    @abstractmethod
    async def get_embeddings(self, texts: list[str]) -> list[list[float]]:
        """Generate batch embeddings for a list of texts."""
        pass

    @property
    @abstractmethod
    def dimension(self) -> int:
        """The dimensionality of the vector generated by this provider (e.g. 768, 1536)."""
        pass
